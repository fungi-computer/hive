import { chromium } from "playwright";

const base = process.argv[2] ?? "http://127.0.0.1:5207/three-depth-study.html";
const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROMIUM_PATH });
const page = await browser.newPage({ viewport: { width: 1100, height: 760 }, deviceScaleFactor: 1 });
const errors = [];
page.on("console", message => { if (message.type() === "error") errors.push(`console: ${message.text()}`); });
page.on("pageerror", error => errors.push(`page: ${error.message}`));
await page.goto(base, { waitUntil: "domcontentloaded" });
await page.locator("#status").waitFor({ state: "visible", timeout: 30000 });
await page.waitForTimeout(500);
const canvas = page.locator("canvas");
const baseline = await canvas.screenshot();
const frameSamples = await page.evaluate(() => new Promise(resolve => {
  const samples = []; let previous = performance.now(), count = 0;
  const tick = now => { samples.push(now - previous); previous = now; if (++count < 90) requestAnimationFrame(tick); else resolve(samples); };
  requestAnimationFrame(tick);
}));
await page.screenshot({ path: "evidence/20260920-three-depth-first-shape.png", fullPage: true });
await canvas.click({ position: { x: 320, y: 200 } });
await page.getByRole("button", { name: "E ▶" }).click();
await page.getByRole("button", { name: "Layer −" }).click();
await page.getByRole("button", { name: "Reset view" }).click();
await page.getByRole("button", { name: "Water: off" }).click();
await page.getByRole("button", { name: "Water: on" }).click();
await page.getByRole("button", { name: "Repeat view loop" }).click();
await page.selectOption("#preset", "dense");
await page.getByRole("button", { name: "Evict chunks" }).click();
await page.getByRole("button", { name: "Rebuild chunks" }).click();
await page.screenshot({ path: "evidence/20260920-three-depth-controls.png", fullPage: true });
await page.selectOption("#preset", "court");
await page.getByRole("button", { name: "Reset view" }).click();
await page.waitForTimeout(100);
const warm = await canvas.screenshot();
await page.reload({ waitUntil: "domcontentloaded" });
await page.locator("#status").waitFor({ state: "visible", timeout: 30000 });
await page.waitForTimeout(500);
const cold = await canvas.screenshot();
const pixelsEqual = Buffer.compare(baseline, warm) === 0 && Buffer.compare(baseline, cold) === 0;
const sortedFrames = [...frameSamples].sort((a, b) => a - b);
const percentile = p => sortedFrames[Math.min(sortedFrames.length - 1, Math.floor(sortedFrames.length * p))];
const result = { title: await page.title(), status: await page.locator("#status").textContent(), canvas: await canvas.evaluate(node => ({ width: node.width, height: node.height, dpr: devicePixelRatio })), frameMs: { median: percentile(.5), p95: percentile(.95), max: Math.max(...frameSamples) }, pixelsEqual, errors };
console.log(JSON.stringify(result, null, 2));
if (errors.length || !pixelsEqual) process.exitCode = 1;
await browser.close();
